/* 词法分析器：支持中英双语关键字、字符串插值、自动分号（换行即语句结束） */
#ifndef GZG_LEXER_H
#define GZG_LEXER_H

#include "common.h"

typedef enum {
    /* 符号 */
    TOKEN_LEFT_PAREN, TOKEN_RIGHT_PAREN, TOKEN_LEFT_BRACE, TOKEN_RIGHT_BRACE,
    TOKEN_LEFT_BRACKET, TOKEN_RIGHT_BRACKET,
    TOKEN_COMMA, TOKEN_DOT, TOKEN_SEMICOLON, TOKEN_COLON, TOKEN_QUESTION,
    TOKEN_PLUS, TOKEN_MINUS, TOKEN_STAR, TOKEN_SLASH, TOKEN_PERCENT,
    TOKEN_STAR_STAR, TOKEN_SLASH_SLASH,
    TOKEN_PLUS_EQUAL, TOKEN_MINUS_EQUAL, TOKEN_STAR_EQUAL, TOKEN_SLASH_EQUAL, TOKEN_PERCENT_EQUAL,
    TOKEN_BANG, TOKEN_BANG_EQUAL, TOKEN_EQUAL, TOKEN_EQUAL_EQUAL, TOKEN_FAT_ARROW,
    TOKEN_GREATER, TOKEN_GREATER_EQUAL, TOKEN_LESS, TOKEN_LESS_EQUAL,
    TOKEN_AMP, TOKEN_PIPE, TOKEN_CARET, TOKEN_TILDE, TOKEN_SHL, TOKEN_SHR,
    TOKEN_AMP_AMP, TOKEN_PIPE_PIPE, TOKEN_PIPE_GT,
    TOKEN_DOT_DOT, TOKEN_DOT_DOT_EQ,
    /* 字面量 */
    TOKEN_IDENTIFIER, TOKEN_STRING, TOKEN_RAW_STRING, TOKEN_INTERP, TOKEN_INT, TOKEN_FLOAT,
    /* 关键字 */
    TOKEN_LET, TOKEN_CONST, TOKEN_FN, TOKEN_RETURN, TOKEN_IF, TOKEN_ELIF, TOKEN_ELSE,
    TOKEN_WHILE, TOKEN_FOR, TOKEN_IN, TOKEN_BREAK, TOKEN_CONTINUE,
    TOKEN_STRUCT, TOKEN_SELF, TOKEN_MATCH, TOKEN_TRY, TOKEN_CATCH, TOKEN_THROW,
    TOKEN_IMPORT, TOKEN_AND, TOKEN_OR, TOKEN_NOT, TOKEN_TRUE, TOKEN_FALSE, TOKEN_NIL,
    /* 其他 */
    TOKEN_NEWLINE, TOKEN_ERROR, TOKEN_EOF,
    TOKEN_COUNT
} TokenType;

typedef struct {
    TokenType type;
    const char* start;
    int length;
    int line;
    int column;     /* 从 1 开始，按显示宽度（中文算 2） */
} Token;

void initLexer(const char* source);
Token scanToken(void);
const char* tokenTypeName(TokenType type);
const char* lexerSource(void);

#endif
